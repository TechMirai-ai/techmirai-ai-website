import type { BookableService, CustomerInput, ErrorResponse } from '../../api/schemas'

export type { BookableService, CustomerInput, ErrorResponse } from '../../api/schemas'

/**
 * schemas.ts is pure zod with no Node/Payload dependencies — the same
 * bundle-isolation reason client.ts documents for why it only imports
 * schemas.ts, not the booking/api barrel, applies here too: this module is
 * bundled into a 'use client' component tree.
 */

export type FlowStep = 'visit-type' | 'service' | 'calendar' | 'contact' | 'confirmation' | 'success'

/** Order used for default "go back one step" navigation and the progress indicator. */
export const FLOW_STEPS: readonly FlowStep[] = ['visit-type', 'service', 'calendar', 'contact', 'confirmation', 'success']

export type VisitType = 'first' | 'return'

export interface SelectedSlot {
  slotId: string | number
  resourceId: string | number
  startsAt: string
  endsAt: string
}

export type SubmissionState = 'idle' | 'submitting' | 'error' | 'success'

export interface ReserveResult {
  confirmationCode: string
  accessToken: string
  // Expiring credential for the on-screen "manage your appointment" link —
  // see tokens.ts's deriveLinkToken. Never the raw accessToken in the link.
  linkToken: string
}

export interface FlowState {
  step: FlowStep
  visitType?: VisitType | undefined
  service?: BookableService | undefined
  slot?: SelectedSlot | undefined
  customer?: CustomerInput | undefined
  /**
   * STEP 2 Part 2 item 6 (LIFF returning-patient shortcut) — true only when
   * this flow instance was SEEDED at init with a known customer (see
   * useBookingFlow.ts's buildInitialState), never set by any later action.
   * Deliberately NOT derived from `customer` being truthy: customer also
   * gets set by the ordinary web flow's SUBMIT_CONTACT_FORM and stays set
   * across GO_BACK (by design — it repopulates the form on a
   * back-then-forward navigation), so using its mere presence as the
   * "skip the contact step" signal would wrongly skip contact for a normal
   * web user who backs up twice from confirmation and picks a new slot.
   */
  skipContactStep: boolean
  /**
   * Generated once, on ENTER_CONTACT_STEP, and never regenerated for the
   * life of this flow instance — see the reducer's guard. Reused on every
   * reserve()/retry so a double-tapped submit cannot create two appointments.
   */
  idempotencyKey: string | null
  submission: SubmissionState
  submitError?: ErrorResponse['error'] | undefined
  reserveResult?: ReserveResult | undefined
}

export const INITIAL_FLOW_STATE: FlowState = {
  step: 'visit-type',
  skipContactStep: false,
  idempotencyKey: null,
  submission: 'idle',
}

export type FlowAction =
  | { type: 'SELECT_VISIT_TYPE'; visitType: VisitType }
  | { type: 'SELECT_SERVICE'; service: BookableService }
  | { type: 'SELECT_SLOT'; slot: SelectedSlot }
  // idempotencyKey is generated by the caller (useBookingFlow.ts, via
  // createIdempotencyKey() from booking/client) and passed in here, so the
  // reducer itself never imports crypto and stays trivially unit-testable.
  | { type: 'ENTER_CONTACT_STEP'; idempotencyKey: string }
  | { type: 'SUBMIT_CONTACT_FORM'; customer: CustomerInput }
  | { type: 'CONFIRM_SUBMIT' }
  | { type: 'RESERVE_SUCCEEDED'; result: ReserveResult }
  | { type: 'RESERVE_FAILED'; error: ErrorResponse['error'] }
  // `to`, when set, forces a specific destination (e.g. SLOT_FULL/SLOT_CLOSED
  // routing back to 'calendar' from 'confirmation') and clears the now-stale
  // slot selection. Omitted, it just steps back one position in FLOW_STEPS.
  | { type: 'GO_BACK'; to?: FlowStep | undefined }
